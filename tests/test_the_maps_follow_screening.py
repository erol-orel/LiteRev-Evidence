def test_a_cleared_cache_is_not_resurrected_from_memory(corpus, monkeypatch):
    """Every invalidation (threshold, narrowing, living review, screening) clears the
    database copy; a result the job had written there is then stale, not a fallback."""
    import threading
    started: list = []
    monkeypatch.setattr(threading, "Thread", lambda target=None, args=(), daemon=None: started.append(target)
                        or _SyncThread(target=lambda *a: None))
    with corpus.cursor() as cur:            # what subsets and the living review do: SQL only
        cur.execute("UPDATE scenario_settings SET clustering_json = NULL, clustering_generated_at = NULL"
                    " WHERE scenario_id = %s", (SID,))
    main._clustering_jobs[SID] = {"status": "done", "result": _PAYLOAD, "persisted": True}
    status = main.get_user_scenario_clustering_status(SID, "fr")
    assert status["status"] == "not_started"
    res = main.get_user_scenario_clustering(SID, False, "fr")
    assert res["status"] == "running" and started, "the stale clustering was served from memory"
    # A result the database never received (a corpus too small, a failed write) is still
    # served from memory, as before.
    small = {"scenario_id": SID, "n_docs": 2, "clusters": [], "message_code": "insufficient_corpus"}
    main._clustering_jobs[SID] = {"status": "done", "result": small}
    assert main.get_user_scenario_clustering(SID, False, "fr")["n_docs"] == 2
    assert json.dumps(main.get_user_scenario_clustering_status(SID, "fr"))
