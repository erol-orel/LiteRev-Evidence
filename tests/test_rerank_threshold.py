def _relevant(thr: float = 0.3) -> set[int]:
    from sqlalchemy import text
    sql = (f"SELECT d.id FROM literature_document d"
           f" JOIN article_scenarios ars ON ars.document_id = d.id"
           f" WHERE ars.scenario_id = :sid AND {relevant_gate_sql()}")
    with main.engine.connect() as conn:
        return {r[0] for r in conn.execute(text(sql), {"sid": SID, "thr": thr})}


def _set_rerank_threshold(value) -> None:
    from sqlalchemy import text
    with main.engine.begin() as conn:
        conn.execute(text(
            "INSERT INTO scenario_settings (scenario_id, rerank_threshold)"
            " VALUES (:sid, :v) ON CONFLICT (scenario_id)"
            " DO UPDATE SET rerank_threshold = :v"), {"sid": SID, "v": value})


def test_with_no_setting_at_all_the_gate_is_exactly_the_old_one(seeded):
    """Aucune ligne de réglages : la colonne ne peut pas filtrer."""
    assert _relevant() == {1, 2, 3, 5}          # 4 est sous le seuil de similarité


def test_a_zero_threshold_changes_nothing(seeded):
    _set_rerank_threshold(0)
    assert _relevant() == {1, 2, 3, 5}


def test_a_null_threshold_changes_nothing(seeded):
    """La colonne existe mais n'a jamais été réglée : NULL vaut 0, pas « tout exclure »."""
    _set_rerank_threshold(None)
    assert _relevant() == {1, 2, 3, 5}


def test_the_rerank_cut_drops_the_off_topic_article_the_similarity_cut_could_not(seeded):
    """Le coeur de la fonctionnalité.

    L'article 2 a une similarité PLUS HAUTE que l'article 1. Aucun seuil de similarité ne
    peut retirer 2 en gardant 1. Le rerank le fait."""
    _set_rerank_threshold(0.26)
    kept = _relevant()
    assert 1 in kept, "l'article du sujet a été jeté"
    assert 2 not in kept, "l'article hors sujet a survécu"


def test_no_similarity_threshold_can_do_the_same(seeded):
    """La démonstration par l'absurde, pour que personne ne retire ce code en croyant
    qu'un curseur suffisait."""
    for thr in (0.30, 0.35, 0.37, 0.39, 0.401):
        kept = _relevant(thr)
        assert not (1 in kept and 2 not in kept), (
            f"à {thr}, la similarité aurait séparé les deux : le test ne prouve plus rien")


def test_an_article_not_yet_reranked_survives_any_cut(seeded):
    """45 des 602 pertinents du corpus HPAI étaient dans ce cas."""
    for thr in (0.1, 0.5, 0.95, 1.0):
        _set_rerank_threshold(thr)
        assert 3 in _relevant(), f"l'article non reranké a disparu au seuil {thr}"


def test_a_hand_included_article_survives_the_rerank_cut(seeded):
    """Le rerank ne peut pas défaire la décision d'un relecteur."""
    _set_rerank_threshold(0.95)
    assert 5 in _relevant()


def test_the_rerank_cut_does_not_rescue_an_article_below_the_similarity_cut(seeded):
    """Les deux seuils se cumulent, ils ne se remplacent pas : l'article 4 a le meilleur
    rerank du lot et reste dehors, parce que sa similarité est sous le seuil."""
    _set_rerank_threshold(0.5)
    assert 4 not in _relevant()


def test_the_two_counters_agree_with_the_gate(seeded):
    """Le compteur du corpus passe par la même porte : il doit bouger avec elle."""
    from sqlalchemy import text
    _set_rerank_threshold(0.26)
    with main.engine.connect() as conn:
        row = conn.execute(text(main.scenario_counts_sql()),
                           {"sid": SID, "thr": 0.3}).mappings().first()
    assert int(row["relevant"]) == len(_relevant())


# ─── Le réglage, par l'API ───────────────────────────────────────────────────

def test_a_threshold_outside_zero_one_is_refused(seeded):
    from fastapi import HTTPException
    for bad in (45, -0.1, 1.5):
        with pytest.raises(HTTPException) as e:
            main.update_scenario_settings(SID, {"rerank_threshold": bad}, None)
        assert e.value.status_code == 422
    with pytest.raises(HTTPException):
        main.update_scenario_settings(SID, {"rerank_threshold": "beaucoup"}, None)


def test_the_setting_round_trips(seeded):
    out = main.update_scenario_settings(SID, {"rerank_threshold": 0.26}, None)
    assert out["rerank_threshold"] == pytest.approx(0.26)
    assert main.get_scenario_settings(SID)["rerank_threshold"] == pytest.approx(0.26)


def test_an_unset_scenario_reads_as_zero_not_as_null(seeded):
    """L'interface affiche ce nombre sur un curseur : None l'aurait laissé vide."""
    assert main.get_scenario_settings(SID)["rerank_threshold"] == DEFAULT_RERANK_THRESHOLD


def test_moving_the_rerank_threshold_invalidates_the_derived_caches(seeded):
    """Le clustering et les actions recommandées sont des fonctions du corpus, et le
    rerank découpe le corpus autant que la similarité."""
    from sqlalchemy import text
    with main.engine.begin() as conn:
        conn.execute(text(
            "INSERT INTO scenario_settings (scenario_id, clustering_json)"
            " VALUES (:sid, '{\"stale\": true}'::jsonb) ON CONFLICT (scenario_id)"
            " DO UPDATE SET clustering_json = '{\"stale\": true}'::jsonb"), {"sid": SID})
    main.update_scenario_settings(SID, {"rerank_threshold": 0.4}, None)
    with main.engine.connect() as conn:
        left = conn.execute(text(
            "SELECT clustering_json FROM scenario_settings WHERE scenario_id = :sid"),
            {"sid": SID}).scalar()
    assert left is None, "le clustering d'avant la coupe était encore servi"


