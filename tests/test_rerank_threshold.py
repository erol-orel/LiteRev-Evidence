"""Un second seuil, sur le score de rerank, parce que le premier ne sépare pas.

Mesuré sur le scénario HPAI (602 articles pertinents) : les articles hors sujet ont une
similarité MÉDIANE PLUS HAUTE que les articles du sujet, 0.398 contre 0.361. Monter le
curseur de similarité y jetait donc d'abord ce qu'on voulait garder. Le rerank sépare les
deux populations, 0.588 contre 0.070.

Ce que ces tests épinglent :

- la porte ne change RIEN par défaut (seuil 0, ou colonne jamais renseignée) ;
- un article sans score de rerank RESTE, là où un article sans similarité SORT. L'asymétrie
  est le coeur de la fonctionnalité : le rerank arrive par lots, et compter l'absence pour
  zéro aurait fait disparaître sans un mot les articles pas encore jugés ;
- un seuil hors de [0, 1] est refusé plutôt qu'appliqué ;
- la courbe du rerank compte les non scorés parmi ceux qui passent d'office.
"""
import pytest

pytest.importorskip("fastapi")

import main  # noqa: E402
from api.scenario_store import (  # noqa: E402
    DEFAULT_RERANK_THRESHOLD,
    relevant_gate_sql,
    scenario_rerank_threshold_sql,
)

SID = "rerank-gate"


def _engine_ok() -> bool:
    try:
        with main.engine.connect():
            return True
    except Exception:
        return False


# ─── La chaîne SQL, sans base ────────────────────────────────────────────────

def test_the_gate_mentions_both_scores():
    sql = relevant_gate_sql()
    assert "similarity_score" in sql and "rerank_score" in sql


def test_an_unscored_rerank_is_let_through_by_the_predicate_itself():
    """Lisible dans la chaîne : la seule façon de ne pas dépendre du lot en cours."""
    assert "ars.rerank_score IS NULL OR" in relevant_gate_sql()


def test_the_rerank_threshold_is_read_in_the_query_not_bound():
    """Quinze appelants partagent cette porte ; aucun n'a de `:rthr` à lier."""
    sql = relevant_gate_sql()
    assert ":rthr" not in sql
    assert "scenario_settings" in sql


def test_the_subquery_is_keyed_on_the_link_row_scenario():
    assert "ars.scenario_id" in scenario_rerank_threshold_sql("ars.scenario_id")


def test_the_default_is_zero_so_the_gate_is_unchanged():
    assert DEFAULT_RERANK_THRESHOLD == 0.0


def test_a_hand_included_article_still_bypasses_both_thresholds():
    sql = relevant_gate_sql()
    head, _, tail = sql.partition("= 'included' OR")
    assert tail, "la branche 'inclus à la main' a disparu de la porte"


