def test_no_reader_of_the_threshold_falls_back_on_a_literal_any_more():
    """The literal sat in relevance.py, scenarios.py and review.py, each with its own
    fallback. search.py's `_search_local_doc_ids(threshold=0.45)` is the vector cut of the
    LOCAL SEARCH, not a reading of a scenario's threshold, and is left to that module."""
    api = pathlib.Path(__file__).resolve().parent.parent / "api"
    offenders = []
    for path in sorted(api.glob("*.py")):
        if path.name in ("scenario_store.py", "search.py"):
            continue
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Constant) and node.value == 0.45:
                offenders.append(f"{path.name}:{node.lineno}")
    assert not offenders, f"a 0.45 literal is back: {offenders}"


# ── Against a real database ──────────────────────────────────────────────────
def _engine_ok() -> bool:
    try:
        with main.engine.connect():
            return True
    except Exception:
        return False


@pytest.fixture()
def settings(db_conn):
    if not _engine_ok():
        pytest.skip("main.engine cannot reach the database")
    from conftest import ensure_document_columns
    with db_conn.cursor() as cur:
        cur.execute("SELECT to_regclass('user_scenarios') IS NULL")
        if cur.fetchone()[0]:
            main._ensure_user_scenarios_table()
        # The counters and the threshold curve read the corpus tables, whatever shape the
        # previous test left them in.
        cur.execute("CREATE TABLE IF NOT EXISTS literature_document (id BIGINT PRIMARY KEY)")
        cur.execute("CREATE TABLE IF NOT EXISTS article_scenarios ("
                    "scenario_id TEXT, document_id BIGINT, PRIMARY KEY (scenario_id, document_id))")
        ensure_document_columns(cur)
        for col, typ in (("title", "TEXT"), ("abstract", "TEXT"), ("journal", "TEXT"),
                         ("is_duplicate", "BOOLEAN DEFAULT FALSE")):
            cur.execute(f"ALTER TABLE literature_document ADD COLUMN IF NOT EXISTS {col} {typ}")
        cur.execute("ALTER TABLE article_scenarios ADD COLUMN IF NOT EXISTS similarity_score DOUBLE PRECISION")
        # The boot DDL is what drops the default and adds the dating column: run it, as a
        # deployment does on start.
        main._ensure_scenario_settings_table()
        for sid in (SID, LEGACY, CHOSEN):
            cur.execute("DELETE FROM scenario_settings WHERE scenario_id = %s", (sid,))
            cur.execute("DELETE FROM user_scenarios WHERE id = %s", (sid,))
            cur.execute("INSERT INTO user_scenarios (id, name, query, mode, filters) "
                        "VALUES (%s, 'Threshold', 'dengue', 'boolean', '{}')", (sid,))
        # Two rows written BEFORE the change: the old default, and a value someone chose.
        cur.execute("INSERT INTO scenario_settings (scenario_id, similarity_threshold) "
                    "VALUES (%s, 0.45), (%s, 0.6)", (LEGACY, CHOSEN))
    yield db_conn
    with db_conn.cursor() as cur:
        for sid in (SID, LEGACY, CHOSEN):
            cur.execute("DELETE FROM scenario_settings WHERE scenario_id = %s", (sid,))
            cur.execute("DELETE FROM user_scenarios WHERE id = %s", (sid,))


def _client():
    from fastapi.testclient import TestClient
    return TestClient(main.app)


def test_the_column_no_longer_writes_a_value_nobody_chose(settings):
    with settings.cursor() as cur:
        cur.execute("SELECT column_default FROM information_schema.columns "
                    "WHERE table_name = 'scenario_settings' AND column_name = 'similarity_threshold'")
        assert cur.fetchone()[0] is None
    # A row created for another reason (here a visualisation cache) stores no threshold.
    main._save_viz_cache(SID, "kg", {"nodes": []})
    with settings.cursor() as cur:
        cur.execute("SELECT similarity_threshold FROM scenario_settings WHERE scenario_id = %s", (SID,))
        assert cur.fetchone()[0] is None
    info = main.scenario_threshold_info(SID)
    assert info == {"threshold": 0.45, "chosen": False, "set_at": None}


def test_a_row_from_before_counts_as_chosen_only_when_it_is_not_the_old_default(settings):
    assert main.scenario_threshold_info(LEGACY)["chosen"] is False
    chosen = main.scenario_threshold_info(CHOSEN)
    assert chosen["chosen"] is True and chosen["threshold"] == 0.6
    assert main.scenario_threshold_info("usr-no-settings-row")["chosen"] is False


def test_setting_the_threshold_is_a_choice_even_at_the_starting_value(settings):
    r = _client().patch(f"/scenarios/{SID}/settings", json={"similarity_threshold": 0.45}, headers=KEY)
    assert r.status_code == 200, r.text
    assert r.json()["threshold_chosen"] is True and r.json()["similarity_threshold"] == 0.45
    body = _client().get(f"/scenarios/{SID}/settings").json()
    assert body["threshold_chosen"] is True and body["similarity_threshold_set_at"]


def test_setting_only_the_rerank_threshold_chooses_nothing_else(settings):
    r = _client().patch(f"/scenarios/{SID}/settings", json={"rerank_threshold": 0.2}, headers=KEY)
    assert r.status_code == 200, r.text
    assert r.json()["threshold_chosen"] is False
    body = _client().get(f"/scenarios/{SID}/settings").json()
    assert body["threshold_chosen"] is False and body["similarity_threshold"] == 0.45
    assert _client().get("/scenarios/usr-no-settings-row/settings").json()["threshold_chosen"] is False


def test_a_new_starting_value_reaches_every_scenario_nobody_chose_for(settings, monkeypatch):
    """The point of storing nothing: the Python reader and the SQL reader both follow the
    constant for a row nobody chose, and both keep a value somebody did choose."""
    from sqlalchemy import text
    patch_app(monkeypatch, "DEFAULT_SIMILARITY_THRESHOLD", 0.5)
    from api.scenario_store import scenario_threshold_sql
    with main.engine.connect() as conn:
        def _sql(sid):
            return conn.execute(text(f"SELECT {scenario_threshold_sql(':sid')}"), {"sid": sid}).scalar()
        assert _sql(LEGACY) == 0.5 and main.scenario_threshold_info(LEGACY)["threshold"] == 0.5
        assert _sql(CHOSEN) == 0.6 and main.scenario_threshold_info(CHOSEN)["threshold"] == 0.6
    assert main.scenario_counts(LEGACY)["threshold"] == 0.5


def test_the_threshold_curve_says_whether_the_current_threshold_was_chosen(settings):
    assert _client().get(f"/scenarios/{LEGACY}/threshold-curve").json()["current_threshold_chosen"] is False
    assert _client().get(f"/scenarios/{CHOSEN}/threshold-curve").json()["current_threshold_chosen"] is True
