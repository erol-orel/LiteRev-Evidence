"""An article without a similarity score counts 0 at the gate: it stays out of the
relevant set until something scores it. The rule is fine; the scorer had holes.

- the OpenAI fallback stopped at 200 batches of 100, so past 20,000 not-yet-embedded
  articles the rest stayed unscored, with a log line as the only trace;
- the first failed batch broke the loop, so one transient error left the rest unscored;
- during the 300-second OpenAI cooldown the fallback did not run at all, silently;
- the automatic scoring ran once per process: after one "done", articles linked or
  embedded later stayed unscored until a pipeline run, a restart or a manual recompute.

Each is pinned here against a real database, with a fake embedding model. These
fixtures have no pgvector, so the fast path fails and is reported; the fallback, which
needs none, runs on its own, which is also what it now does in that case.
"""
import time

import pytest

pytest.importorskip("fastapi")

import main  # noqa: E402
from api import relevance as R  # noqa: E402

SID = "usr-noholes-0001"


class _D:
    def __init__(self, embedding, index):
        self.embedding, self.index = embedding, index


class _Resp:
    def __init__(self, data):
        self.data = data


def _fake_openai(calls, fail_on=(), always_fail=False, quota=False):
    """Query embedding = (1, 0); every article = (0.6, 0.8), so every score is 0.6.
    `fail_on`: the numbers (1-based) of the article batches that raise."""
    class _Embeddings:
        def create(self, model=None, input=None, **kw):
            if isinstance(input, str):
                return _Resp([_D([1.0, 0.0], 0)])
            calls.append(list(input))
            if always_fail or len(calls) in fail_on:
                raise RuntimeError("insufficient_quota" if quota else "upstream hiccup")
            return _Resp([_D([0.6, 0.8], i) for i in range(len(input))])

    class _Client:
        def __init__(self, *a, **k):
            self.embeddings = _Embeddings()
    return _Client


def _engine_ok() -> bool:
    try:
        with main.engine.connect():
            return True
    except Exception:
        return False


@pytest.fixture()
def corpus(db_conn, monkeypatch):
    """`n` articles with an abstract, plus one without any usable text, all unscored."""
    if not _engine_ok():
        pytest.skip("main.engine cannot reach the database")
    scheduled: list = []
    monkeypatch.setattr(R, "_schedule_autoscore", lambda sid, delay: scheduled.append((sid, delay)))
    monkeypatch.setattr(R, "_AUTOSCORE", {})
    monkeypatch.setattr(R, "_RERANK_JOBS", {})
    monkeypatch.setenv("OPENAI_API_KEY", "sk-test")         # the fake model below answers
    # The cooldown is a one-element list shared by every module: saved and restored by
    # hand (monkeypatch.setitem only knows mappings).
    cooldown = main.core._OPENAI_QUOTA_COOLDOWN_UNTIL
    saved_cooldown = cooldown[0]
    cooldown[0] = 0.0

    def _make(n: int):
        with db_conn.cursor() as cur:
            cur.execute("DROP TABLE IF EXISTS document_search")
            cur.execute("DROP TABLE IF EXISTS document_chunk, article_scenarios, literature_document CASCADE")
            cur.execute(
                "CREATE TABLE literature_document ("
                "id bigint PRIMARY KEY, title text NOT NULL, source text NOT NULL DEFAULT 'pubmed',"
                "abstract text, year int, is_duplicate boolean DEFAULT false, journal text,"
                "citation_count int, created_at timestamptz DEFAULT now(),"
                "project_context text DEFAULT 'literev')")
            cur.execute(
                "CREATE TABLE document_chunk ("
                "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                "document_id bigint NOT NULL REFERENCES literature_document(id) ON DELETE CASCADE,"
                "chunk_index int DEFAULT 0, content text, chunk_type text, embedding text,"
                "created_at timestamp DEFAULT now())")
            cur.execute(
                "CREATE TABLE article_scenarios (scenario_id text, document_id bigint,"
                "similarity_score double precision, rerank_score double precision,"
                "screening_status text, reviewer_1_status text, reviewer_2_status text,"
                "PRIMARY KEY (scenario_id, document_id))")
            cur.execute("SELECT to_regclass('user_scenarios') IS NULL")
            if cur.fetchone()[0]:
                main._ensure_user_scenarios_table()
            cur.execute("SELECT to_regclass('scenario_settings') IS NULL")
            if cur.fetchone()[0]:
                main._ensure_scenario_settings_table()
            cur.execute("DELETE FROM user_scenarios WHERE id = %s", (SID,))
            cur.execute("DELETE FROM scenario_settings WHERE scenario_id = %s", (SID,))
            cur.execute("INSERT INTO user_scenarios (id, name, query, mode, filters) "
                        "VALUES (%s, 'No holes', 'avian influenza', 'boolean', '{}')", (SID,))
            cur.executemany("INSERT INTO literature_document (id, title, abstract) VALUES (%s, %s, %s)",
                            [(i, f"Article {i}", "an abstract long enough to be scored") for i in range(1, n + 1)])
            cur.execute("INSERT INTO literature_document (id, title, abstract) VALUES (9999, 'Tiny', NULL)")
            cur.executemany("INSERT INTO article_scenarios (scenario_id, document_id) VALUES (%s, %s)",
                            [(SID, i) for i in list(range(1, n + 1)) + [9999]])
        return db_conn

    yield _make, scheduled
    cooldown[0] = saved_cooldown
    with db_conn.cursor() as cur:
        cur.execute("DELETE FROM user_scenarios WHERE id = %s", (SID,))
        cur.execute("DELETE FROM scenario_settings WHERE scenario_id = %s", (SID,))


def _unscored(conn) -> int:
    with conn.cursor() as cur:
        cur.execute("SELECT COUNT(*) FROM article_scenarios WHERE scenario_id = %s"
                    " AND similarity_score IS NULL AND document_id <> 9999", (SID,))
        return cur.fetchone()[0]


def test_the_fallback_has_no_ceiling_any_more(corpus, monkeypatch):
    """200 batches was the old ceiling. 203 batches of one article all get scored."""
    make, _ = corpus
    conn = make(203)
    calls: list = []
    import llm_usage
    monkeypatch.setattr(llm_usage, "MeteredOpenAI", _fake_openai(calls))
    monkeypatch.setattr(R, "_FALLBACK_BATCH", 1)
    rep: dict = {}
    n = R._run_semantic_rerank_inline(SID, "avian influenza", report=rep)
    assert len(calls) == 203 and n == 203 and _unscored(conn) == 0
    assert rep["fallback"] == 203 and rep["unscored"] == 1   # the article with no text at all
    assert rep["retryable"] == 0


