class _SyncThread:
    def __init__(self, target=None, args=(), kwargs=None, daemon=None):
        self.target, self.args, self.kwargs = target, args, kwargs or {}

    def start(self):
        self.target(*self.args, **self.kwargs)


def test_the_automatic_scoring_rearms_while_articles_stay_unscored(corpus, monkeypatch):
    """It ran once per process: after one "done", nothing scored the articles linked
    later until a restart."""
    import threading

    import llm_usage
    make, _ = corpus
    conn = make(6)
    monkeypatch.setattr(llm_usage, "MeteredOpenAI", _fake_openai([]))
    monkeypatch.setattr(threading, "Thread", _SyncThread)
    assert R._maybe_autorerank(SID) is True
    assert R._RERANK_JOBS[SID]["status"] in ("done", "partial") and _unscored(conn) == 0
    # A new article is linked after that run (living review, a worker, a rebuild).
    with conn.cursor() as cur:
        cur.execute("INSERT INTO literature_document (id, title, abstract) VALUES (7, 'Late', "
                    "'an abstract that arrived after the first run')")
        cur.execute("INSERT INTO article_scenarios (scenario_id, document_id) VALUES (%s, 7)", (SID,))
    # Not in a tight loop: the next pass waits for its interval...
    assert R._maybe_autorerank(SID) is False
    # ... and once it has elapsed, the scoring passes again instead of staying "done".
    R._AUTOSCORE[SID]["not_before"] = 0.0
    assert R._maybe_autorerank(SID) is True
    assert _unscored(conn) == 0


def test_nothing_is_launched_for_articles_no_pass_can_score(corpus, monkeypatch):
    """The article without any text stays unscored for ever: relaunching for it would be
    a job per page view."""
    import threading
    make, _ = corpus
    conn = make(0)
    launched: list = []
    monkeypatch.setattr(threading, "Thread", lambda *a, **k: launched.append(k) or _SyncThread())
