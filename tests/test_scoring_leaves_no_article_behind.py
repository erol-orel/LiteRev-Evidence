    assert R._AUTOSCORE[SID]["not_before"] > time.time()
    with conn.cursor() as cur:
        cur.execute("SELECT COUNT(*) FROM article_scenarios WHERE scenario_id = %s", (SID,))
        assert cur.fetchone()[0] == 1


